// Flattens the HeatSync Labs mark (assets/brand/hsl-mark-paths.json, traced
// from the official logo) into polylines the cart fills with an even-odd
// scanline rasterizer. The mark is used untouched: two colours, no smoothing.
//
//   node tools/gen-logo.mjs <hsl-mark-paths.json> <out.h>
import { readFileSync, writeFileSync } from 'node:fs';

const [src, out] = process.argv.slice(2);
const paths = JSON.parse(readFileSync(src, 'utf8'));
const TX = -26, TY = -4; // the official SVG's group transform

function flatten(d) {
  const toks = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g);
  const rings = [];
  let ring = null, cmd = null, i = 0, x = 0, y = 0, sx = 0, sy = 0;
  const num = () => parseFloat(toks[i++]);
  const push = (px, py) => ring.push([px + TX, py + TY]);
  while (i < toks.length) {
    if (/[a-zA-Z]/.test(toks[i])) cmd = toks[i++];
    switch (cmd) {
      case 'M': case 'm': {
        const nx = num(), ny = num();
        x = cmd === 'm' ? x + nx : nx; y = cmd === 'm' ? y + ny : ny;
        sx = x; sy = y; ring = []; rings.push(ring); push(x, y);
        cmd = cmd === 'm' ? 'l' : 'L'; // implicit lineto after moveto
        break;
      }
      case 'L': case 'l': {
        const nx = num(), ny = num();
        x = cmd === 'l' ? x + nx : nx; y = cmd === 'l' ? y + ny : ny; push(x, y);
        break;
      }
      case 'H': case 'h': { const n = num(); x = cmd === 'h' ? x + n : n; push(x, y); break; }
      case 'V': case 'v': { const n = num(); y = cmd === 'v' ? y + n : n; push(x, y); break; }
      case 'C': case 'c': {
        let p = [num(), num(), num(), num(), num(), num()];
        if (cmd === 'c') p = p.map((v, k) => v + (k % 2 ? y : x));
        const [x1, y1, x2, y2, x3, y3] = p;
        const steps = 8;
        for (let s = 1; s <= steps; s++) {
          const t = s / steps, u = 1 - t;
          push(u * u * u * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3,
               u * u * u * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3);
        }
        x = x3; y = y3;
        break;
      }
      case 'Z': case 'z': x = sx; y = sy; break;
      default: throw new Error(`unsupported path command ${cmd}`);
    }
  }
  return rings.filter((r) => r.length > 2);
}

function emit(name, list) {
  const rings = list.flatMap(flatten);
  const pts = [], starts = [];
  for (const r of rings) { starts.push(pts.length / 2); for (const [px, py] of r) pts.push(px.toFixed(1), py.toFixed(1)); }
  starts.push(pts.length / 2);
  return `static const float ${name}_pts[] = {${pts.join(',')}};\n` +
    `static const int ${name}_ring[] = {${starts.join(',')}};\n` +
    `#define ${name.toUpperCase()}_RINGS ${rings.length}\n`;
}

writeFileSync(out,
  '/* generated by tools/gen-logo.mjs from the official HeatSync Labs mark. 1000x1000 units. */\n' +
  emit('logo_sun', [].concat(paths.sun)) + emit('logo_flame', [].concat(paths.flame)));
